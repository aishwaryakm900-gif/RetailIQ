export function buildDemoCatalogue(shopId: string, now: Date = new Date()) {
  const products: Product[] = [];
  const batches: Batch[] = [];

  DEMO_PRODUCTS.forEach((seed) => {
    products.push({
      id: seed.id,
      shopId,
      name: seed.name,
      barcode: seed.barcode,
      sku: seed.sku,
      category: seed.category,
      mrp: seed.mrp,
      purchasePrice: seed.purchasePrice,
      sellingPrice: seed.sellingPrice,
      minStock: seed.minStock,
      reorderLevel: seed.reorderLevel,
      supplierId: seed.supplierId,
      shelfLifeDays: seed.shelfLifeDays,
      dailyDemandAvg: seed.dailyDemandAvg,
      moverState: seed.moverState,
      imageEmoji: seed.imageEmoji,
      imageUrl: seed.imageUrl,
    });

    seed.batches.forEach((batchSeed, batchIndex) => {
      const mfgOffset = Math.min(-1, batchSeed.expiryOffset - seed.shelfLifeDays);
      batches.push({
        id: `batch-${seed.id}-${batchIndex + 1}`,
        shopId,
        productId: seed.id,
        batchNo: batchSeed.batchNo,
        mfgDate: addDaysIso(now, mfgOffset),
        expiryDate: addDaysIso(now, batchSeed.expiryOffset),
        qtyReceived: batchSeed.qtyReceived,
        qtyOnHand: batchSeed.qtyOnHand,
        costPrice: batchSeed.costPrice,
      });
    });
  });

  const activities: ActivityEvent[] = [
    {
      id: 'act-demo-catalogue',
      shopId,
      type: 'product',
      message: 'Catalogue updated with 20 products across 8 categories',
      timestamp: 'Just now',
    },
    {
      id: 'act-demo-expiry',
      shopId,
      type: 'expiry',
      message: '4 products are expiring within the next 7 days',
      timestamp: '2 hours ago',
    },
    {
      id: 'act-demo-low',
      shopId,
      type: 'low_stock',
      message: '5 products are below their minimum stock level',
      timestamp: 'Today',
    },
  ];

  return { products, batches, activities };
}
